#!/usr/bin/env node
// senior-design-review: build scripts/bundle.js = settle.js + measure.js + space.js + batch.js with comments and indentation stripped,
// so a browser-tool session pastes one smaller script once per tab. Run after editing any of the three.
// Usage: node scripts/bundle.mjs   (writes bundle.js beside this file, prints its size and the expected function lengths)
// Pasting bundle.js into a page returns "sdr ready {...lengths}": compare with the lengths printed here. A mismatch means
// the paste was altered (a transcription slip): paste again.
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const strip = src => src.split('\n')
  .filter(l => !/^\s*\/\//.test(l))                 // whole-line comments only; inline code is left alone
  .map(l => l.trim()).filter(Boolean).join('\n');
const parts = ['settle.js', 'measure.js', 'space.js', 'batch.js'].map(f => `/* ${f} */\n` + strip(readFileSync(join(here, f), 'utf8')) + ';');
const lengths = "'sdr ready ' + JSON.stringify(Object.fromEntries(Object.entries(window.__sdr).map(([k, f]) => [k, String(f).length])))";
const out = '// senior-design-review bundle (generated by bundle.mjs; edit the sources, not this file)\n' + parts.join('\n') + '\n' + lengths + '\n';
new Function(out); // fails loudly if stripping broke the syntax
writeFileSync(join(here, 'bundle.js'), out);
// Expected lengths: evaluate each part in a bare context; the functions register before their first run fails without a DOM.
const ctx = vm.createContext({}); ctx.window = ctx;
for (const part of parts) { try { const r = vm.runInContext(part, ctx); r?.then?.(() => {}, () => {}); } catch { /* no DOM here; registration already happened */ } }
const expected = Object.fromEntries(Object.entries(ctx.__sdr || {}).map(([k, f]) => [k, String(f).length]));
console.log(`bundle.js ${(out.length / 1024).toFixed(1)} KB\nexpected lengths ${JSON.stringify(expected)}`);
